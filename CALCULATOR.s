    CMP  R0, #0            ; PREGUNTO SI LLEGA A 0  SI NO SIGO CONVIRTIENDO DIGITOS Y GUARDANDO EN PILA
    BNE  ConvertLoop

    ; Extraer dígitos de la pila (en orden inverso)
    MOV R6, R3             ; Copiar contador
    LDR R1, =RES           ; Recargar dirección de RES
