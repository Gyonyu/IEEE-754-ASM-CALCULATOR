	MOV  R2, #10           ; Base decimal
    MOV  R3, #1            ; Inicializar factor (10^0 = 1)
    MOV  R5, R1            ; Copiar contador de dígitos
CALFAC
    MUL  R3, R3, R2        ; R3 = R3 * 10
    SUBS R5, R5, #1        ; Decrementar contador
    BNE  CALFAC   ; Repetir hasta completar

    ; Multiplicar fracción por factor de escala
    ; (R0 * R3) >> 32 (aritmética de 64 bits)
    UMULL R4, R5, R0, R3   ; [R5:R4] = R0 * R3 (64 bits)
    
    ; El resultado entero está en R5 (parte alta de 64 bits)
    MOV  R0, R5            ; Mover resultado a R0
    
    ; Contar dígitos del resultado
    MOV  R1, #0            ; Inicializar contador de dígitos
    MOV  R2, #10           ; Divisor
CONTARDIGITOS
