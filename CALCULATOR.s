USART1_IRQHandler
	PUSH{LR}
	CMP R5,#1
	BEQ NUMERO2
	CMP R5,#2	
	BEQ OPERANDO
	LDR R0,=USART_DR
	LDR R1,[R0]
	BL.W WRITE_UART
	LDR R0,=USART_DR
	LDR R1,[R0]
	CMP R1,#'-'
	BLEQ.W MENOS1
	LDR R0,=NUM1
	ADD R0,R4,R0
	STRB R1,[R0]
	ADD R4,#1
	CMP R1,#0X0D;CUANDO PRESIONO ENTER ENTRA AL SIGUIENTE NUMERO PARA GUARDAR
	BEQ PART1
	POP{LR}
	BX LR
MENOS1
	MOV R9,#1
	POP{LR}
	BX LR
MENOS2
	MOV R8,#1
	POP{LR}
	BX LR
ERROR
	MOV R1,#0X0D
	BL WRITE_UART
	MOV R1,#0X0A
	BL WRITE_UART
	MOV R1,'E'
	BL WRITE_UART
	MOV R1,'R'
	BL WRITE_UART
	MOV R1,'R'
	BL WRITE_UART
	MOV R1,'O'
	BL WRITE_UART
	MOV R1,'R'
	BL WRITE_UART
	B .
PART1
	ADD R5,#1
	EOR R4,R4
	MOV R1,#0X0A
	BL.W WRITE_UART
	POP{LR}
	BX LR
NUMERO2
	LDR R0,=USART_DR
	LDR R1,[R0]
	BL WRITE_UART
	LDR R0,=USART_DR
	LDR R1,[R0]
	CMP R1,#'-'
	BLEQ MENOS2
	LDR R0,=NUM2
	ADD R0,R4,R0
	STRB R1,[R0]
	ADD R4,#1
	CMP R1,#0X0D
	BEQ PART1
	POP{LR}
	BX LR
	
OPERANDO
	LDR R0,=USART_DR
	LDR R1,[R0]
	BL WRITE_UART
	LDR R0,=USART_DR
	LDR R1,[R0]
	CMP R1,#'+'
	BLNE POKER
	LDR R0,=OPER
	ADD R0,R4,R0
	STRB R1,[R0]
	ADD R4,#1
	CMP R1,#0X0D;CUANDO COLOCO MI OPERACION Y DOY ENTER ENTRO A LA PARTE DE INTERPRETAR MIS ASCII
	BEQ REGRESOFINAL
	POP{LR}
	BX LR
REGRESOFINAL
	EOR R7,R7
	ADD R7,#1
	POP{LR}
	BX LR
POKER
	CMP R1,#0X0D
	BEQ PK1
	CMP R1,#'-'
	BNE ERROR
PK1	BX LR

